#!/usr/bin/env bash
# Generate a compose override that lets the browser reach Datadog's RUM intake
# on networks whose DNS blocks it.
#
# WHY THIS EXISTS
# ===============
# Some corporate networks (this one runs DNSFilter) return NODATA for
# *.browser-intake-datadoghq.com while leaving api.datadoghq.com alone. The
# Agent therefore ships traces, logs and metrics perfectly, and Browser RUM
# goes completely dark — with no error anywhere, because the SDK simply cannot
# resolve its intake host.
#
# The block is DNS-only: the intake answers normally when reached by IP. So
# pinning the addresses into the containers' /etc/hosts restores RUM.
#
# Addresses are resolved over DNS-over-HTTPS, which bypasses port-53
# interception, and re-resolved every run — these are AWS addresses and they
# DO rotate, which is why this is a stopgap and not a fix.
#
# THE ACTUAL FIX is to have the domains allowlisted in your DNS filter:
#   browser-intake-datadoghq.com
#   session-replay.browser-intake-datadoghq.com
# (adjust for your DD_SITE; US1 shown). Ask whoever runs the filter.
#
# This override only affects containers. Your own browser on the host still
# needs the allowlist (or a hosts entry, which needs sudo).
#
# Usage:
#   make rum-unblock
#   COMPOSE_FILE=compose.yaml:docker-compose.override.yaml:docker-compose.rum-dns.yaml make up

set -uo pipefail

red()    { printf '\033[31m%s\033[0m\n' "$*"; }
green()  { printf '\033[32m%s\033[0m\n' "$*"; }
yellow() { printf '\033[33m%s\033[0m\n' "$*"; }

SITE="${DD_SITE:-datadoghq.com}"
OUT="docker-compose.rum-dns.yaml"

# Intake hosts the Browser RUM SDK uses, derived from the site.
HOSTS=(
  "browser-intake-${SITE}"
  "session-replay.browser-intake-${SITE}"
)

doh() {
  curl -sS --max-time 10 -H 'accept: application/dns-json' \
    "https://cloudflare-dns.com/dns-query?name=$1&type=A" 2>/dev/null \
  | python3 -c '
import json, sys
try: d = json.load(sys.stdin)
except Exception: sys.exit(1)
ips = [a["data"] for a in (d.get("Answer") or []) if a.get("type") == 1]
print(ips[0] if ips else "")
'
}

echo "Resolving the RUM intake for site '${SITE}' over DNS-over-HTTPS..."
declare -a ENTRIES=()
declare -a ENTRY_IPS=()
for h in "${HOSTS[@]}"; do
  ip=$(doh "$h")
  if [[ -z "$ip" ]]; then
    red "  ${h}: could not resolve over DoH"
    exit 1
  fi
  green "  ${h} -> ${ip}"
  ENTRIES+=("    - \"${h}:${ip}\"")
  ENTRY_IPS+=("${ip}")
done

# Is local DNS actually blocking it? If not, this override is unnecessary.
if getent hosts "${HOSTS[0]}" >/dev/null 2>&1; then
  yellow
  yellow "NOTE: ${HOSTS[0]} already resolves through your normal DNS, so this"
  yellow "override is probably unnecessary. Writing it anyway is harmless, but"
  yellow "prefer plain DNS — pinned IPs go stale."
fi

{
  echo "# Generated by scripts/rum-unblock.sh on the machine that ran it."
  echo "# DO NOT COMMIT: these are point-in-time AWS addresses for the Datadog"
  echo "# RUM intake, resolved over DoH because this network's DNS blocks the"
  echo "# name. They rotate. Re-run 'make rum-unblock' if RUM goes quiet."
  echo "#"
  echo "# The real fix is a DNS allowlist entry - see scripts/rum-unblock.sh."
  echo "services:"
  echo "  web:"
  echo "    build:"
  echo "      args:"
  echo "        # Switches the RUM SDK to same-origin delivery via /dd-rum."
  echo "        VITE_DD_RUM_PROXY: /dd-rum"
  echo "    volumes:"
  echo "    - ./web/rum-proxy:/etc/nginx/rum-proxy:ro"
  echo "    extra_hosts:"
  printf '%s\n' "${ENTRIES[@]}"
  echo "  load:"
  echo "    extra_hosts:"
  printf '%s\n' "${ENTRIES[@]}"
} > "$OUT"

# ---------------------------------------------------------------------------
# The nginx snippet that actually rescues the operator's own browser.
#
# extra_hosts above only ever helped containers. A human opening the app on
# this laptop resolves through the host's blocked DNS, so the RUM SDK is
# instead pointed at /dd-rum on the app's own origin (a same-origin request
# needs no lookup of the blocked name) and nginx forwards it to the intake.
#
# Datadog's RUM proxy contract: the SDK appends ?ddforward=<encoded intake
# path and query>, and the proxy must forward to the intake preserving it.
#
# proxy_pass targets the IP LITERAL, not the hostname. nginx only needs a
# `resolver` when the address is a name, and no resolver on this network could
# answer for this name anyway. SNI and the Host header are set explicitly so
# TLS still validates against the real certificate.
# ---------------------------------------------------------------------------
RUM_IP="${ENTRY_IPS[0]}"
SNIPPET_DIR="web/rum-proxy"
mkdir -p "$SNIPPET_DIR"
cat > "${SNIPPET_DIR}/dd-rum.conf" <<NGINX
# Generated by scripts/rum-unblock.sh - do not edit, do not commit.
# Pins ${HOSTS[0]} at ${RUM_IP}. Re-run 'make rum-unblock' if RUM goes quiet.
#
# The storefront's RUM SDK is configured with the FUNCTION form of \`proxy\`, so it
# posts to /dd-rum<intake-path>?<intake-query> - a real path, not a
# percent-encoded ddforward parameter. That means this block only has to strip
# the prefix and forward, with no URL decoding (nginx cannot decode
# \$arg_* values, which is what made the ddforward approach return 502).
#
# The trailing slash on both the location and proxy_pass is what performs the
# prefix strip: /dd-rum/api/v2/rum -> /api/v2/rum.
location /dd-rum/ {
    proxy_pass https://${RUM_IP}/;

    # We dialled an IP because the name is unresolvable on this network, so
    # SNI and Host must still carry the real hostname for TLS to validate.
    proxy_ssl_server_name on;
    proxy_ssl_name ${HOSTS[0]};
    proxy_set_header Host ${HOSTS[0]};

    # RUM derives geo and device from these, so do not let them be rewritten.
    proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;
    proxy_set_header User-Agent \$http_user_agent;

    proxy_http_version 1.1;
    proxy_connect_timeout 5s;
    proxy_read_timeout 15s;

    # Same-origin from the browser's point of view, so the intake's own CORS
    # headers are irrelevant and would only confuse the response.
    proxy_hide_header Access-Control-Allow-Origin;
}
NGINX

green
green "wrote ${OUT}"
green "wrote ${SNIPPET_DIR}/dd-rum.conf (pins ${RUM_IP})"
echo
echo "Both are picked up automatically by 'make up'."
echo "Rebuild the storefront so the proxy setting is baked into the bundle:"
echo "  make up"
echo
echo "This fixes BOTH the containers and your own browser. The permanent fix"
echo "is still a DNS allowlist entry for:"
for h in "${HOSTS[@]}"; do echo "  ${h}"; done
